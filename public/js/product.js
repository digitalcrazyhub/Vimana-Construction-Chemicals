const productGrid = document.getElementById("pitvmxProductGrid");


/* ============================================================
   CREATE PRODUCT CARDS
============================================================ */

function renderProducts() {

    if (!productGrid) {
        return;
    }

    productGrid.innerHTML = "";

    products.forEach((product, index) => {

        const card = document.createElement("article");

        card.className = "pitvmx-card";

        card.innerHTML = `
            
            <div class="pitvmx-image-wrapper">

                <img
                    class="pitvmx-image pitvmx-gallery-image"
                    src="${product.image}"
                    alt="${product.name}"
                    data-product-index="${index}"
                    loading="lazy"
                    draggable="false"
                >

                <span class="pitvmx-badge">
                    ${product.badge}
                </span>

            </div>


            <div class="pitvmx-content">

                <h3 class="pitvmx-card-title">
                    ${product.name}
                </h3>

                <p class="pitvmx-card-text">
                    ${product.description || ""}
                </p>

                <a
                    href="tel:+917845404310"
                    class="pitvmx-button"
                    aria-label="Call for more details about ${product.name}"
                >
                    <span>More Details</span>

                    <i
                        data-lucide="phone-call"
                        aria-hidden="true"
                    ></i>

                </a>

            </div>

        `;

        productGrid.appendChild(card);

    });


    /* Re-render Lucide icons after creating cards */

    if (typeof lucide !== "undefined") {
        lucide.createIcons();
    }

}


