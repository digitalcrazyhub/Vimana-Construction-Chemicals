/* ============================================================
   LIGHTBOX VARIABLES
============================================================ */

let pitvmxImages = [];

let pitvmxIndex = 0;


/* ============================================================
   OPEN LIGHTBOX
============================================================ */

function openLightbox(productIndex) {

    const product = products[productIndex];

    if (!product) {
        return;
    }

    if (!product.gallery || product.gallery.length === 0) {
        return;
    }

    pitvmxImages = product.gallery;

    pitvmxIndex = 0;

    updateLightboxImage();

    if (pitvmxLightbox) {

        pitvmxLightbox.classList.add("pitvmx-open");

        pitvmxLightbox.setAttribute("aria-hidden", "false");

    }

    document.body.style.overflow = "hidden";

}


/* ============================================================
   UPDATE LIGHTBOX IMAGE
============================================================ */

function updateLightboxImage() {

    if (!pitvmxLightboxImage) {
        return;
    }

    if (!pitvmxImages.length) {
        return;
    }

    pitvmxLightboxImage.src =
        pitvmxImages[pitvmxIndex];

    pitvmxLightboxImage.alt =
        `Product image ${pitvmxIndex + 1}`;

}


